#!/usr/bin/env node
/**
 * Builds the committed REMS ground-temperature sample for Gale.
 *
 * Source: the mars.nasa.gov MSL weather feed, Centro de Astrobiología's
 * outreach copy of the Curiosity REMS record, one row per sol since
 * landing, `min_gts_temp` / `max_gts_temp` in integer °C
 * (`src/data/temperature/remsGaleFeed.ts`). The app reads it live and never
 * commits it. This script commits the one exception:
 * a sample for the temperature model's validation test,
 * which must run offline. It keeps every Nth sol that has both a minimum
 * and a maximum, in the feed's own row shape with only the five fields the
 * adapter reads, so `parseRemsFeed` validates the sample as it would the
 * feed. Rows are written oldest first.
 *
 * Run:  node scripts/build-rems-extract.mjs [--every 20] [--from <saved feed.json>]
 * Out:  tests/fixtures/remsGaleSampled.ts, typed `unknown`
 */
import { readFileSync, writeFileSync } from 'node:fs'

const FEED_URL = 'https://mars.nasa.gov/rss/api/?feed=weather&category=msl&feedtype=json&ver=1.0'
const OUT = 'tests/fixtures/remsGaleSampled.ts'
const FIELDS = ['sol', 'terrestrial_date', 'ls', 'min_gts_temp', 'max_gts_temp']

const args = parseArgs(process.argv.slice(2))
const every = Number(args.every ?? 20)
if (!Number.isInteger(every) || every < 1) fail('--every must be a whole number of sols')

const builtOn = new Date().toISOString().slice(0, 10)
// With --from, the copy's own fetch date is not known to the script; the run's date is not it.
const fetchedOn = args.from ? `a saved copy of the feed, fetched on or before ${builtOn}` : builtOn
const body = args.from ? JSON.parse(readFileSync(args.from, 'utf8')) : await (await fetch(FEED_URL)).json()
if (!Array.isArray(body?.soles)) fail('the feed has no "soles" list')

const hasValue = (v) => typeof v === 'string' && v.trim() !== '' && v.trim() !== '--'
const rows = body.soles
  .filter((r) => hasValue(r.min_gts_temp) && hasValue(r.max_gts_temp))
  .map((r) => Object.fromEntries(FIELDS.map((f) => [f, String(r[f])])))
  .sort((a, b) => Number(a.sol) - Number(b.sol))
const sampled = rows.filter((_, i) => i % every === 0)
const latest = body.soles.reduce((m, r) => Math.max(m, Number(r.sol)), 0)
const disclaimer = String(body.descriptions?.disclaimer_en ?? '')
  .replace(/\s+/g, ' ')
  .trim()

const provenance = {
  feed: FEED_URL,
  builtOn,
  fetchedOn,
  solsInFeed: body.soles.length,
  latestSol: latest,
  solsWithBothValues: rows.length,
  rule: `every ${every}th sol with both min_gts_temp and max_gts_temp, oldest first; the five fields the adapter reads, as the feed prints them (integer °C as strings)`,
  disclaimer,
  builtWith: 'scripts/build-rems-extract.mjs',
}

const header = [
  `// Generated by scripts/build-rems-extract.mjs on ${builtOn}. Do not edit: run the script.`,
  '// OFFICIAL, outreach copy: Curiosity REMS ground temperature per sol, mars.nasa.gov MSL weather feed (CAB). A test fixture only: the app reads the feed live.',
  '// Typed unknown on purpose: remsGaleFeed.ts validates every row before a number leaves this file.',
].join('\n')
const out =
  `${header}\nexport const REMS_GALE_SAMPLE_PROVENANCE = ${JSON.stringify(provenance, null, 2)} as const\n\n` +
  `export const REMS_GALE_SAMPLED_RAW: unknown = {"soles":[\n${sampled.map((r) => JSON.stringify(r)).join(',\n')}\n]}\n`
writeFileSync(OUT, out)
console.log(`${sampled.length} of ${rows.length} sols with both values (feed: ${body.soles.length} sols to sol ${latest}) → ${OUT}`)

function parseArgs(argv) {
  const out = {}
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith('--')) out[argv[i].slice(2)] = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : true
  }
  return out
}
function fail(msg) {
  console.error(`✗ ${msg}`)
  process.exit(1)
}
